#' Estimate Standardized Regression Coefficients
#' and Generate the Corresponding Sampling Distribution
#' Using the Monte Carlo Method
#'
#' @details By default, both \eqn{y} and the regressors are standardized.
#'   With `std_y = FALSE`, \eqn{y} is left in its original units
#'   (\eqn{b_j \sigma_{x_j}});
#'   with `std_x`, only the named regressors are standardized
#'   (for example, `std_x = character(0)` gives \eqn{b_j / \sigma_y},
#'   and leaving a dummy variable out of `std_x` keeps its 0-1 contrast).
#'   The standard deviations are taken from each draw.
#'
#'   The vector of standardized regression coefficients
#'   (\eqn{\boldsymbol{\hat{\beta}}})
#'   is derived from each randomly generated vector of parameter estimates.
#'   Confidence intervals are generated by obtaining
#'   percentiles corresponding to \eqn{100(1 - \alpha)\%}
#'   from the generated sampling
#'   distribution of \eqn{\boldsymbol{\hat{\beta}}},
#'   where \eqn{\alpha} is the significance level.
#'
#' @author Ivan Jacob Agaloos Pesigan
#'
#' @return Returns an object
#'   of class `betamc` which is a list with the following elements:
#'   \describe{
#'     \item{call}{Function call.}
#'     \item{args}{Function arguments.}
#'     \item{thetahatstar}{Sampling distribution of
#'       \eqn{\boldsymbol{\hat{\beta}}}.}
#'     \item{vcov}{Sampling variance-covariance matrix of
#'       \eqn{\boldsymbol{\hat{\beta}}}.}
#'     \item{est}{Vector of estimated
#'       \eqn{\boldsymbol{\hat{\beta}}}.}
#'     \item{fun}{Function used ("BetaMC").}
#'   }
#'
#' @param object Object of class `mc`, that is,
#'   the output of the `MC()` function.
#' @param alpha Numeric vector.
#'   Significance level \eqn{\alpha}.
#' @param std_y Logical.
#'   Standardize \eqn{y}.
#' @param std_x Character vector or `NULL`.
#'   Names of the regressors to standardize.
#'   `NULL` (default) standardizes all regressors;
#'   `character(0)` standardizes none.
#'
#' @examples
#' # Data ---------------------------------------------------------------------
#' data("nas1982", package = "betaMC")
#'
#' # Fit Model in lm ----------------------------------------------------------
#' object <- lm(QUALITY ~ NARTIC + PCTGRT + PCTSUPP, data = nas1982)
#'
#' # MC -----------------------------------------------------------------------
#' mc <- MC(
#'   object,
#'   R = 100, # use a large value e.g., 20000L for actual research
#'   seed = 0508
#' )
#'
#' # BetaMC -------------------------------------------------------------------
#' out <- BetaMC(mc, alpha = 0.05)
#'
#' ## Methods -----------------------------------------------------------------
#' print(out)
#' summary(out)
#' coef(out)
#' vcov(out)
#' confint(out, level = 0.95)
#'
#' @family Beta Monte Carlo Functions
#' @keywords betaMC std
#' @export
BetaMC <- function(object,
                   alpha = c(0.05, 0.01, 0.001),
                   std_y = TRUE,
                   std_x = NULL) {
  stopifnot(
    inherits(
      x = object,
      what = "mc"
    )
  )
  index <- .BetaStarSelectIndex(
    std_x = std_x,
    xnames = object$lm_process$xnames
  )
  if (object$fun == "MCMI") {
    est <- colMeans(
      do.call(
        what = "rbind",
        args = lapply(
          X = object$args$mi_output$lm_process,
          FUN = function(x) {
            .BetaStarSelectLM(
              lm_process = x,
              std_y = std_y,
              std_x = index
            )
          }
        )
      )
    )
  } else {
    est <- .BetaStarSelectLM(
      lm_process = object$lm_process,
      std_y = std_y,
      std_x = index
    )
  }
  if (std_y && all(index)) {
    thetahatstar <- object$es$betastar
  } else {
    thetahatstar <- .BetaStarSelectofVechSigmaMat(
      betastar = object$es$betastar,
      vechsigmacap = object$vechsigmacap,
      k = object$lm_process$k,
      std_y = std_y,
      std_x = index
    )
  }
  out <- list(
    call = match.call(),
    args = list(
      object = object,
      alpha = alpha,
      std_y = std_y,
      std_x = std_x
    ),
    thetahatstar = thetahatstar,
    est = est,
    fun = "BetaMC"
  )
  class(out) <- c(
    "betamc",
    class(out)
  )
  out
}
