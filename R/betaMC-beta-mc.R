#' Estimate Standardized Regression Coefficients
#' and Generate the Corresponding Sampling Distribution
#' Using the Monte Carlo Method
#'
#' @details By default, both \eqn{y} and the regressors are standardized.
#'   With `std_y = FALSE`, \eqn{y} is left in its original units
#'   (\eqn{b_j \sigma_{x_j}});
#'   with `std_x`, only the named regressors are standardized
#'   (for example, `std_x = character(0)` gives \eqn{b_j / \sigma_y},
#'   and leaving a dummy variable out of `std_x` keeps its 0-1 contrast).
#'   The standard deviations are taken from each draw.
#'
#'   The vector of standardized regression coefficients
#'   (\eqn{\boldsymbol{\hat{\beta}}})
#'   is derived from each randomly generated vector of parameter estimates.
#'   Confidence intervals are generated by obtaining
#'   percentiles corresponding to \eqn{100(1 - \alpha)\%}
#'   from the generated sampling
#'   distribution of \eqn{\boldsymbol{\hat{\beta}}},
#'   where \eqn{\alpha} is the significance level.
#'
#' @details
#' From the regression parameters
#' \eqn{\boldsymbol{\theta} = \left\{ \boldsymbol{b}, \sigma^{2},
#' \operatorname{vech} \left( \boldsymbol{\Sigma}_{\boldsymbol{X}
#' \boldsymbol{X}} \right) \right\}} of each draw (see [MC()]),
#' the variance of the outcome and the standardized regression slopes are
#' \deqn{\sigma^{2}_{y} = \boldsymbol{b}^{\prime}
#' \boldsymbol{\Sigma}_{\boldsymbol{X} \boldsymbol{X}} \boldsymbol{b} +
#' \sigma^{2}, \quad \beta^{\ast}_{j} = b_{j}
#' \frac{\sigma_{x_{j}}}{\sigma_{y}},}
#' where \eqn{\sigma_{x_{j}}} is the square root of the \eqn{j}th diagonal
#' element of \eqn{\boldsymbol{\Sigma}_{\boldsymbol{X} \boldsymbol{X}}}.
#' The estimates are computed from the fitted model,
#' the draws \eqn{\hat{\boldsymbol{\beta}}^{\ast}_{r}} from each Monte Carlo
#' draw, and `vcov` is the sample covariance matrix of the draws.
#' The percentile interval is
#' \eqn{\left[ \hat{G}^{-1} \left( \alpha / 2 \right), \hat{G}^{-1} \left( 1 -
#' \alpha / 2 \right) \right]},
#' where \eqn{\hat{G}} is the empirical distribution function of the draws.
#'
#' @author Ivan Jacob Agaloos Pesigan
#'
#' @return Returns an object
#'   of class `betamc` which is a list with the following elements:
#'   \describe{
#'     \item{call}{Function call.}
#'     \item{args}{Function arguments.}
#'     \item{thetahatstar}{Sampling distribution of
#'       \eqn{\boldsymbol{\hat{\beta}}}.}
#'     \item{vcov}{Sampling variance-covariance matrix of
#'       \eqn{\boldsymbol{\hat{\beta}}}.}
#'     \item{est}{Vector of estimated
#'       \eqn{\boldsymbol{\hat{\beta}}}.}
#'     \item{fun}{Function used ("BetaMC").}
#'   }
#'
#' @param object Object of class `mc`, that is,
#'   the output of the `MC()` function.
#' @param alpha Numeric vector.
#'   Significance level \eqn{\alpha}.
#' @param std_y Logical.
#'   Standardize \eqn{y}.
#' @param std_x Character vector or `NULL`.
#'   Names of the regressors to standardize.
#'   `NULL` (default) standardizes all regressors;
#'   `character(0)` standardizes none.
#'
#' @examples
#' # Data ---------------------------------------------------------------------
#' data("nas1982", package = "betaMC")
#'
#' # Fit Model in lm ----------------------------------------------------------
#' object <- stats::lm(
#'   formula = QUALITY ~ NARTIC + PCTGRT + PCTSUPP,
#'   data = nas1982
#' )
#'
#' # MC -----------------------------------------------------------------------
#' mc <- MC(
#'   object = object,
#'   R = 100, # use a large value e.g., 20000L for actual research
#'   seed = 0508
#' )
#'
#' # BetaMC -------------------------------------------------------------------
#' out <- BetaMC(object = mc, alpha = 0.05)
#'
#' ## Methods -----------------------------------------------------------------
#' print(x = out)
#' summary(object = out)
#' coef(object = out)
#' vcov(object = out)
#' confint(object = out, level = 0.95)
#'
#' @references
#' Dudgeon, P. (2017).
#' Some improvements in confidence intervals
#' for standardized regression coefficients.
#' *Psychometrika*, *82*(4), 928--951.
#' \doi{10.1007/s11336-017-9563-z}
#'
#' MacKinnon, D. P., Lockwood, C. M., & Williams, J. (2004).
#' Confidence limits for the indirect effect:
#' Distribution of the product and resampling methods.
#' *Multivariate Behavioral Research*, *39*(1), 99--128.
#' \doi{10.1207/s15327906mbr3901_4}
#'
#' Pesigan, I. J. A., & Cheung, S. F. (2024).
#' Monte Carlo confidence intervals for the indirect effect with missing data.
#' *Behavior Research Methods*.
#' \doi{10.3758/s13428-023-02114-4}
#'
#' Preacher, K. J., & Selig, J. P. (2012).
#' Advantages of Monte Carlo confidence intervals for indirect effects.
#' *Communication Methods and Measures*, *6*(2), 77--98.
#' \doi{10.1080/19312458.2012.679848}
#'
#' @family Beta Monte Carlo Functions
#' @keywords betaMC std
#' @export
BetaMC <- function(object,
                   alpha = c(0.05, 0.01, 0.001),
                   std_y = TRUE,
                   std_x = NULL) {
  stopifnot(
    inherits(
      x = object,
      what = "mc"
    )
  )
  index <- .BetaStarSelectIndex(
    std_x = std_x,
    xnames = object$lm_process$xnames
  )
  if (object$fun == "MCMI") {
    est <- colMeans(
      x = do.call(
        what = "rbind",
        args = lapply(
          X = object$args$mi_output$lm_process,
          FUN = function(x) {
            .BetaStarSelectLM(
              lm_process = x,
              std_y = std_y,
              std_x = index
            )
          }
        )
      )
    )
  } else {
    est <- .BetaStarSelectLM(
      lm_process = object$lm_process,
      std_y = std_y,
      std_x = index
    )
  }
  if (std_y && all(index)) {
    thetahatstar <- object$es$betastar
  } else {
    thetahatstar <- .BetaStarSelectofVechSigmaMat(
      betastar = object$es$betastar,
      vechsigmacap = object$vechsigmacap,
      k = object$lm_process$k,
      std_y = std_y,
      std_x = index
    )
  }
  out <- list(
    call = match.call(),
    args = list(
      object = object,
      alpha = alpha,
      std_y = std_y,
      std_x = std_x
    ),
    thetahatstar = thetahatstar,
    est = est,
    fun = "BetaMC"
  )
  class(x = out) <- c(
    "betamc",
    class(x = out)
  )
  out
}
